/**
 * 永続化を担う層。MyBatis の Mapper インターフェースを置く。
 *
 * クラス名は XxxMapper、Mapper 注釈を付けたインターフェースとして定義し、
 * 実装クラスは書かない（MyBatis が実行時に生成する）。層としての役割は JPA を使う場合と
 * 同じなので、パッケージ名は repository のままにしてある。
 *
 * SQL はインターフェースに書かない。Select などの注釈は使わず、すべて
 * src/main/resources/mapper/XxxMapper.xml に置く。インターフェースはメソッド
 * シグネチャだけを持つ。理由は次の3つ。
 *
 *   - 注釈と XML が混在すると「この SQL はどちらにあるか」を毎回探すことになる。
 *     単純なものは注釈、という線引きは運用のうちに必ず崩れる。
 *
 *   - 動的 SQL（if, foreach）と resultMap は XML でしかまともに書けない。
 *     後から XML へ引っ越す手間を最初から省く。
 *
 *   - SQL が .xml に集まっていれば、実行される SQL の全量をファイル検索で把握できる。
 *
 * XML の namespace は Mapper インターフェースの完全修飾名と一致させる。ずれると
 * 起動時ではなくそのメソッドを呼んだ時点で BindingException になる。
 *
 * 引数が2つ以上あるメソッドは各引数に Param 注釈を付ける。省略すると XML から
 * #{param1} でしか参照できず、意味が読めない SQL になる。
 *
 * 戻り値の型は domain のモデルか、その List。単一件の取得は Optional を使ってよい
 * （MyBatis が対応している）。
 *
 * 更新系メソッドの戻り値 int（更新件数）を捨てないこと。MyBatis にダーティチェックは
 * 無く、楽観ロックも自動では効かない。「更新したつもりで0件だった」を検出できるのは、
 * 呼び出し側でこの件数を見たときだけになる。
 *
 * ここに業務判断を持ち込まないこと。「予約可能な部屋を返す」ではなく
 * 「指定時間帯に予約が存在しない部屋を返す」という、検索条件としての語彙で書く。
 */
